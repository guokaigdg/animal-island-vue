#!/usr/bin/env node
/**
 * 生成内置图标注册表。
 *
 * 数据源：
 *   - 组件清单：node_modules/naive-icons-vue/dist/index.d.ts（随 npm 依赖升级自动变）
 *   - 分类归属：上游 naive-icons 的全量目录 catalog.md
 *
 * 用法：
 *   node scripts/gen-icon-registry.mjs [catalog.md 的路径]
 *
 * catalog.md 不在 naive-icons-vue 包里（在同仓库的 naive-icons 包 / 官网仓库里），
 * 路径没给时按顺序找：命令行参数 → 环境变量 NAIVE_ICONS_CATALOG →
 * 兄弟仓库 ../naive-icons/skills/naive-icons/reference/catalog.md。
 */
import { readFileSync, writeFileSync, existsSync } from 'node:fs';
import { resolve, dirname } from 'path';
import { fileURLToPath } from 'url';

const __dirname = dirname(fileURLToPath(import.meta.url));
const ROOT = resolve(__dirname, '..');
const ICON_DIR = resolve(ROOT, 'src/components/Icon');

/** 上游 catalog 的中文分类标题 → 本库的分类 slug */
const CATEGORY_TITLES = {
    界面基础: 'interface',
    操作: 'action',
    文件与媒体: 'media',
    导航方位: 'navigation',
    通信: 'communication',
    自然天气: 'nature',
    动物: 'animals',
    食物饮品: 'food',
    日常物品: 'objects',
    交通工具: 'transport',
    表情: 'emoji',
};

const findCatalog = () => {
    const candidates = [
        process.argv[2],
        process.env.NAIVE_ICONS_CATALOG,
        // 兄弟仓库 / 上游仓库
        resolve(ROOT, '../../naive-icons/skills/naive-icons/reference/catalog.md'),
        resolve(ROOT, '../naive-icons/skills/naive-icons/reference/catalog.md'),
        // React 侧的 naive-icons 包把 skills 一起发出来了
        resolve(ROOT, '../animal-island-ui/node_modules/naive-icons/skills/naive-icons/reference/catalog.md'),
    ].filter(Boolean);
    const found = candidates.find((p) => existsSync(p));
    if (!found) {
        throw new Error(
            `找不到 catalog.md，试过：\n${candidates.map((c) => `  - ${c}`).join('\n')}\n` +
                '用法：node scripts/gen-icon-registry.mjs <catalog.md 路径>'
        );
    }
    return found;
};

// ---------- 1. 组件清单 ----------
const dtsPath = resolve(ROOT, 'node_modules/naive-icons-vue/dist/index.d.ts');
if (!existsSync(dtsPath)) {
    throw new Error('node_modules/naive-icons-vue 没装好，先跑 npm install');
}
const dts = readFileSync(dtsPath, 'utf8');
const exported = [...dts.matchAll(/^export \{ (\w+) \} from '\.\/\w+\.js';$/gm)].map((m) => m[1]);

// ---------- 2. 分类目录 ----------
const catalogPath = findCatalog();
const catalog = readFileSync(catalogPath, 'utf8');
const rows = [];
let current = null;
for (const line of catalog.split('\n')) {
    const h = line.match(/^## (.+?)（\d+ 枚）$/);
    if (h) {
        const slug = CATEGORY_TITLES[h[1]];
        if (!slug) throw new Error(`未知的分类标题：${h[1]}`);
        current = slug;
        continue;
    }
    const r = line.match(/^\| `([a-z0-9-]+)` \| ([^|]+?) \| `(\w+)` \| ([^|]*) \|$/);
    if (r) {
        if (!current) throw new Error(`分类之外的行：${line}`);
        rows.push({ id: r[1], zh: r[2].trim(), component: r[3], category: current });
    }
}

// ---------- 3. 校验 ----------
// 包里的组件清单是唯一事实来源：catalog 可能比发布版多几枚（上游在做的图标），
// 多出来的直接忽略；反过来包里有的图标 catalog 必须给得出分类。
const catalogMap = new Map(rows.map((r) => [r.component, r]));
const missing = exported.filter((c) => !catalogMap.has(c));
if (missing.length) {
    throw new Error(`包里的组件在 catalog 里没有分类：${missing.join(', ')}`);
}
const extra = rows.filter((r) => !exported.includes(r.component));
if (extra.length) {
    console.log(`catalog 里多出 ${extra.length} 枚（包内没有，已忽略）：${extra.map((r) => r.component).join(', ')}`);
}
const bare = (c) => c.replace(/Icon$/, '');
const names = exported.map(bare);
if (new Set(names).size !== names.length) throw new Error('图标裸名有重复');

const sorted = exported
    .map((c) => ({ ...catalogMap.get(c), component: c }))
    .sort((a, b) => a.component.localeCompare(b.component));
const imports = sorted.map((r) => `    ${r.component},`).join('\n');

// ---------- 4. 产物 ----------
writeFileSync(
    resolve(ICON_DIR, '_icons.ts'),
    `// Auto-generated by scripts/gen-icon-registry.mjs — do not edit by hand.
// 数据源：naive-icons-vue 的导出清单，图标集随 npm 依赖升级自动同步。

import {
${imports}
} from 'naive-icons-vue';
import type { Component } from 'vue';

/** Vue 图标组件类型（任意可作为 \`<component :is>\` 的组件） */
export type IconComponent = Component;

/** 图标名（裸名，无 Icon 后缀）→ 图标组件。给 <Icon name="..."> 用。 */
export const ICON_MAP: Record<IconName, IconComponent> = {
${sorted.map((r) => `    ${bare(r.component)}: ${r.component},`).join('\n')}
};

/** 全部内置图标的裸名，按组件名排序。 */
export const ICON_NAMES = [
${sorted.map((r) => `    '${bare(r.component)}',`).join('\n')}
] as const;

/** 图标名联合类型。消费方写的是 \`<Icon name="Heart">\`，不带 Icon 后缀。 */
export type IconName = (typeof ICON_NAMES)[number];
`
);

writeFileSync(
    resolve(ICON_DIR, '_categories.ts'),
    `// Auto-generated by scripts/gen-icon-registry.mjs — do not edit by hand.
// 分类归属取自上游 naive-icons 的全量目录，与图标集一起随 npm 依赖升级同步。

import { ICON_NAMES } from './_icons';

/** 图标分类。分组顺序即 \`ICONS_BY_CATEGORY\` 的展示顺序。 */
export const ICON_CATEGORIES = [
${Object.values(CATEGORY_TITLES)
    .map((s) => `    '${s}',`)
    .join('\n')}
] as const;

export type IconCategory = (typeof ICON_CATEGORIES)[number];

/** 图标名 → 分类。 */
export const ICON_CATEGORY_OF: Record<string, IconCategory> = {
${sorted.map((r) => `    ${bare(r.component)}: '${r.category}',`).join('\n')}
};

/** 分类分组，每组内按图标名排序。 */
export const ICONS_BY_CATEGORY = ICON_CATEGORIES.map((category) => ({
    category,
    icons: ICON_NAMES.filter((name) => ICON_CATEGORY_OF[name] === category),
}));

/** 扁平图标清单：名称 + 分类。 */
export const ICON_LIST = ICON_NAMES.map((name) => ({
    name,
    label: name,
    category: ICON_CATEGORY_OF[name],
}));
`
);

writeFileSync(
    resolve(ICON_DIR, 'icons.ts'),
    `// Auto-generated by scripts/gen-icon-registry.mjs — do not edit by hand.
// 内置图标组件全部来自 npm 包 naive-icons-vue，本文件只做转出。

export {
${imports}
} from 'naive-icons-vue';
`
);

console.log(`图标 ${sorted.length} 枚，分类 ${Object.values(CATEGORY_TITLES).length} 个`);
console.log('已生成：');
console.log('  src/components/Icon/_icons.ts');
console.log('  src/components/Icon/_categories.ts');
console.log('  src/components/Icon/icons.ts');
