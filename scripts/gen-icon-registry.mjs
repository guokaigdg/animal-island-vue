#!/usr/bin/env node
/**
 * 生成 demo 用的图标目录数据。
 *
 * 数据源：
 *   - 组件清单：node_modules/naive-icons-vue/dist/index.d.ts（随 npm 依赖升级自动变）
 *   - 分类归属：naive-icons 包的 skills/naive-icons/reference/catalog.md
 *
 * 用法：
 *   node scripts/gen-icon-registry.mjs [catalog.md 的路径]
 *
 * naive-icons（React 版）与 naive-icons-vue（Vue 版）是同一套图标设计的两个移植，
 * 版本号一一对应；catalog.md 只随 naive-icons 发布，所以这里把它作为 devDependency
 * 一起锁版本，保证分类表与图标集永远同源。
 * 路径没给时按顺序找：命令行参数 → 环境变量 NAIVE_ICONS_CATALOG →
 * node_modules/naive-icons/… → 兄弟仓库 ../naive-icons/…。
 *
 * 产物只服务 demo 站：图标组件本身由 naive-icons-vue 提供，本包不重导出，
 * 所以运行时按名查表、分类分组这些数据没必要进公共 API。
 */
import { readFileSync, writeFileSync, existsSync } from 'node:fs';
import { resolve, dirname } from 'path';
import { fileURLToPath } from 'url';

const __dirname = dirname(fileURLToPath(import.meta.url));
const ROOT = resolve(__dirname, '..');

/**
 * 上游 catalog 的中文分类标题 → 本库的分类 slug。
 *
 * 键的顺序即分类的展示顺序，与上游 catalog.md 的章节顺序保持一致。
 */
const CATEGORY_TITLES = {
    界面基础: 'interface',
    操作: 'action',
    文件与媒体: 'media',
    导航方位: 'navigation',
    通信: 'communication',
    自然天气: 'nature',
    动物: 'animals',
    食物饮品: 'food',
    金融: 'finance',
    日常物品: 'objects',
    办公: 'office',
    设备硬件: 'device',
    建筑场所: 'building',
    工具: 'tools',
    健康医疗: 'health',
    运动: 'sports',
    交通工具: 'transport',
    表情: 'emoji',
};

const findCatalog = () => {
    const candidates = [
        process.argv[2],
        process.env.NAIVE_ICONS_CATALOG,
        // 与图标集同源的 devDependency（naive-icons 与 naive-icons-vue 版本号一一对应）
        resolve(ROOT, 'node_modules/naive-icons/skills/naive-icons/reference/catalog.md'),
        // 兄弟仓库 / 上游仓库
        resolve(ROOT, '../../naive-icons/skills/naive-icons/reference/catalog.md'),
        resolve(ROOT, '../naive-icons/skills/naive-icons/reference/catalog.md'),
        // React 侧的 naive-icons 包把 skills 一起发出来了
        resolve(ROOT, '../animal-island-ui/node_modules/naive-icons/skills/naive-icons/reference/catalog.md'),
    ].filter(Boolean);
    const found = candidates.find((p) => existsSync(p));
    if (!found) {
        throw new Error(
            `找不到 catalog.md，试过：\n${candidates.map((c) => `  - ${c}`).join('\n')}\n` +
                '用法：node scripts/gen-icon-registry.mjs <catalog.md 路径>'
        );
    }
    return found;
};

// ---------- 1. 组件清单 ----------
const dtsPath = resolve(ROOT, 'node_modules/naive-icons-vue/dist/index.d.ts');
if (!existsSync(dtsPath)) {
    throw new Error('node_modules/naive-icons-vue 没装好，先跑 npm install');
}
const dts = readFileSync(dtsPath, 'utf8');
const exported = [...dts.matchAll(/^export \{ (\w+) \} from '\.\/\w+\.js';$/gm)].map((m) => m[1]);

// ---------- 2. 分类目录 ----------
const catalogPath = findCatalog();
const catalog = readFileSync(catalogPath, 'utf8');
const rows = [];
let current = null;
for (const line of catalog.split('\n')) {
    const h = line.match(/^## (.+?)（\d+ 枚）$/);
    if (h) {
        const slug = CATEGORY_TITLES[h[1]];
        if (!slug) throw new Error(`未知的分类标题：${h[1]}`);
        current = { slug, title: h[1] };
        continue;
    }
    const r = line.match(/^\| `([a-z0-9-]+)` \| ([^|]+?) \| `(\w+)` \| ([^|]*) \|$/);
    if (r) {
        if (!current) throw new Error(`分类之外的行：${line}`);
        rows.push({ id: r[1], zh: r[2].trim(), component: r[3], category: current.slug });
    }
}

// ---------- 3. 校验 ----------
// 包里的组件清单是唯一事实来源：catalog 可能比发布版多几枚（上游在做的图标），
// 多出来的直接忽略；反过来包里有的图标 catalog 必须给得出分类。
const catalogMap = new Map(rows.map((r) => [r.component, r]));
const missing = exported.filter((c) => !catalogMap.has(c));
if (missing.length) {
    throw new Error(`包里的组件在 catalog 里没有分类：${missing.join(', ')}`);
}
const extra = rows.filter((r) => !exported.includes(r.component));
if (extra.length) {
    console.log(`catalog 里多出 ${extra.length} 枚（包内没有，已忽略）：${extra.map((r) => r.component).join(', ')}`);
}
const bare = (c) => c.replace(/Icon$/, '');
const names = exported.map(bare);
if (new Set(names).size !== names.length) throw new Error('图标裸名有重复');

const sorted = exported
    .map((c) => ({ ...catalogMap.get(c), component: c }))
    .sort((a, b) => a.component.localeCompare(b.component));

// ---------- 4. 产物：demo 用的中文名表 ----------
// demo 页要展示每枚图标的中文名，手写会随图标集升级立刻漂移，直接从 catalog 取。
writeFileSync(
    resolve(ROOT, 'demo/tools/iconNames.ts'),
    `// Auto-generated by scripts/gen-icon-registry.mjs — do not edit by hand.
// 图标中文名，来源与上游 naive-icons 的全量目录一致。

export const ICON_ZH_NAMES: Record<string, string> = {
${sorted.map((r) => `    ${bare(r.component)}: '${r.zh.replace(/'/g, "\\'")}',`).join('\n')}
};
`
);

// ---------- 5. 产物：demo 用的分类分组 ----------
// 分类归属取自上游 naive-icons 的全量目录，与图标集一起随 npm 依赖升级同步。
const groups = Object.entries(CATEGORY_TITLES).map(([title, slug]) => ({
    slug,
    title,
    icons: sorted.filter((r) => r.category === slug).map((r) => bare(r.component)),
}));

writeFileSync(
    resolve(ROOT, 'demo/tools/iconCategories.ts'),
    `// Auto-generated by scripts/gen-icon-registry.mjs — do not edit by hand.
// 分类归属取自上游 naive-icons 的全量目录，与图标集一起随 npm 依赖升级同步。

export interface IconCategoryGroup {
    /** 分类 slug（稳定标识） */
    slug: string;
    /** 分类中文名 */
    title: string;
    /** 该分类下的图标裸名（无 Icon 后缀），按组件名排序 */
    icons: string[];
}

/** 全部分类，顺序即展示顺序 */
export const ICON_CATEGORY_GROUPS: IconCategoryGroup[] = [
${groups
    .map(
        (g) =>
            `    {\n        slug: '${g.slug}',\n        title: '${g.title}',\n        icons: [\n${g.icons
                .map((n) => `            '${n}',`)
                .join('\n')}\n        ],\n    },`
    )
    .join('\n')}
];
`
);

console.log(`图标 ${sorted.length} 枚，分类 ${Object.values(CATEGORY_TITLES).length} 个`);
console.log('已生成：');
console.log('  demo/tools/iconNames.ts');
console.log('  demo/tools/iconCategories.ts');
